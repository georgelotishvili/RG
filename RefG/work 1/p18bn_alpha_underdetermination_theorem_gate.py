def source_firewall() -> dict[str, object]:
    module = inspect.getmodule(source_firewall)
    source = inspect.getsource(module)
    forbidden_literals = (
        "COD" + "ATA",
        "OBS" + "ERVED",
        "137.03" + "5999177",
    )
    violations = tuple(
        token for token in forbidden_literals if token in source
    )

    tree = ast.parse(source)
    local_imports = tuple(
        sorted(
            {
                node.module
                for node in ast.walk(tree)
                if isinstance(node, ast.ImportFrom)
                and node.module is not None
                and node.module.startswith("p")
            }
        )
    )
    allowed_local_imports = {
        "p18bh_boundary_slot_count_theorem_gate",
        "p18bl_target_free_alpha_kernel_gate",
    }
    disallowed_local_imports = tuple(
        name for name in local_imports if name not in allowed_local_imports
    )
    return {
        "forbidden_literal_violations": violations,
        "local_imports": local_imports,
        "disallowed_local_imports": disallowed_local_imports,
        "reference_module_imported": False,
        "runtime_reference_free": not violations
        and not disallowed_local_imports,
    }


