def _all_true(value: Any) -> bool:
    if isinstance(value, dict):
        return all(_all_true(item) for item in value.values())
    if isinstance(value, (list, tuple)):
        return all(_all_true(item) for item in value)
    return value is True


def _json_safe(value: Any) -> Any:
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    return str(value)



def candidate_screen(gates: Any, calculation_valid: Any) -> dict[str, bool]:
    expected = set(CLAIM_CONTRACT["CANDIDATE_SCREENING_GATES"])
    schema_valid = (
        isinstance(gates, dict)
        and set(gates) == expected
        and all(type(value) is bool for value in gates.values())
        and type(calculation_valid) is bool
    )
    eligible = bool(
        schema_valid and calculation_valid and all(gates.values())
    )
    return {"valid": bool(schema_valid), "eligible": eligible, "promoted": False}


def scope_closure_controls() -> dict[str, bool]:
    scope = CLAIM_CONTRACT.get("SCOPE_CEILING")
    closure = CLAIM_CONTRACT.get("SCIENTIFIC_CLOSURE")
    return {
        "scope_ceiling_exact": (
            isinstance(scope, dict)
            and scope == EXPECTED_SCOPE_CEILING
            and all(type(value) is bool for value in scope.values())
        ),
        "scientific_closure_exact": (
            isinstance(closure, dict)
            and closure == EXPECTED_SCIENTIFIC_CLOSURE
            and all(type(value) is bool for value in closure.values())
        ),
    }


def scientific_controls() -> dict[str, bool]:
    keys = set(CLAIM_CONTRACT["CANDIDATE_SCREENING_GATES"])
    all_true = {key: True for key in keys}
    one_false = dict(all_true)
    one_false[next(iter(keys))] = False
    missing_rejected = all(
        not candidate_screen({key: True for key in keys if key != omitted}, True)["valid"]
        for omitted in keys
    )
    nonboolean_rejected = all(
        not candidate_screen(
            {key: (1 if key == changed else True) for key in keys}, True
        )["valid"]
        for changed in keys
    )
    extra = dict(all_true)
    extra["unregistered"] = True
    eligible = candidate_screen(all_true, True)
    return {
        "definition_is_explicit": bool(CLAIM_CONTRACT["F2A_DEFINITION"]),
        "witness_routes_are_nonexclusive": (
            CLAIM_CONTRACT["ROUTE_POLICY"]["enumerated_routes_exhaustive"] is False
        ),
        "all_required_gates_are_boolean": all(
            isinstance(text, str) and bool(text)
            for text in CLAIM_CONTRACT["CANDIDATE_SCREENING_GATES"].values()
        ),
        "all_true_candidate_is_only_eligible": (
            eligible["valid"] and eligible["eligible"] and not eligible["promoted"]
        ),
        "one_failed_gate_blocks_eligibility": not candidate_screen(one_false, True)["eligible"],
        "every_missing_gate_is_rejected": missing_rejected,
        "every_nonboolean_gate_is_rejected": nonboolean_rejected,
        "extra_gate_is_rejected": not candidate_screen(extra, True)["valid"],
        "invalid_calculation_blocks_eligibility": not candidate_screen(all_true, False)["eligible"],
        **scope_closure_controls(),
    }


def run() -> dict[str, Any]:
    controls = scientific_controls()
    return {
        "artifact": CLAIM_CONTRACT["CLAIM_ID"],
        "valid": _all_true(controls),
        "claim": CLAIM_CONTRACT["CLAIM"],
        "conclusion": (
            "F2a is defined as an internal operational distinction criterion; "
            "no candidate is evaluated here and full F2 remains open."
        ),
        "scope_ceiling": CLAIM_CONTRACT["SCOPE_CEILING"],
        "scientific_closure": CLAIM_CONTRACT["SCIENTIFIC_CLOSURE"],
        "controls": controls,
    }

def main() -> int:
    try:
        report = run()
    except Exception as error:
        report = {
            "artifact": CLAIM_CONTRACT.get("CLAIM_ID", "unknown"),
            "valid": False,
            "error": f"{type(error).__name__}: {error}",
        }
    print(json.dumps(_json_safe(report), ensure_ascii=False, indent=2, sort_keys=True))
    return 0 if report.get("valid") is True else 1


